export const SERVICE_BY_ID: Record<string, ServiceCatalogEntry> = Object.fromEntries(
  SERVICE_CATALOG.map((entry) => [entry.id, entry]),
);

export const SERVICE_IDS = SERVICE_CATALOG.map((entry) => entry.id);

export const WORLD_SERVICES: Record<SystemWorld, ServiceCatalogEntry[]> = {
  system: SERVICE_CATALOG.filter((entry) => entry.world === 'system'),
  network: SERVICE_CATALOG.filter((entry) => entry.world === 'network'),
  hardware: SERVICE_CATALOG.filter((entry) => entry.world === 'hardware'),
};

export const WORLDS: SystemWorld[] = ['system', 'network', 'hardware'];

export function isSystemServiceId(value: string): boolean {
  return Object.prototype.hasOwnProperty.call(SERVICE_BY_ID, value);
}

export function serviceLabel(id: string, locale: SystemLocale): string {
  const entry = SERVICE_BY_ID[id];
  if (!entry) return id;
  return locale === 'ar' ? entry.ar : entry.en;
}

export function shortServiceLabel(id: string, locale: SystemLocale): string {
  const entry = SERVICE_BY_ID[id];
  if (!entry) return id;
  return locale === 'ar' ? entry.shortAr : entry.shortEn;
}

export function worldLabel(world: SystemWorld, locale: SystemLocale): string {
  return locale === 'ar' ? WORLD_META[world].ar : WORLD_META[world].en;
}
