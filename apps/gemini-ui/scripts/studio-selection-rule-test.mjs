import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
import path from 'node:path';
import {createRequire} from 'node:module';
import {selectOrganizationFiles} from '../src/operations/organization-studio-model.ts';
const require=createRequire(import.meta.url),{fixture,bridgeFor,hashSources}=require('./live-organization-fixtures.cjs');
const f=await fixture(8),{engine,source,request}=await bridgeFor(f);
const scan=await engine.scan({sourceId:source.id});
const rule={text:'ITEM-02',extensions:'.TXT، PDF',minimumBytes:'0',maximumBytes:'4096'};
const selected=selectOrganizationFiles(scan.files,rule);assert.equal(selected.error,null);assert.equal(selected.files.length,1);assert.equal(selected.files[0].name,'item-02.txt');
assert.equal(selectOrganizationFiles(scan.files,{...rule,minimumBytes:'50',maximumBytes:'1'}).error,'INVALID_SIZE_RANGE');
assert.equal(selectOrganizationFiles(scan.files,{...rule,minimumBytes:'NaN'}).error,'INVALID_SIZE_RANGE');
assert.equal(selectOrganizationFiles(scan.files,{...rule,extensions:'../txt'}).error,'INVALID_EXTENSION');
assert.equal(selectOrganizationFiles(scan.files,{...rule,text:'absent'}).files.length,0);
const plan=await engine.plan({...request,fileIds:selected.files.map(file=>file.id)});assert.equal(plan.totals.files,1);
const moved=await engine.execute({planId:plan.planId,planHash:plan.planHash,approved:true});assert.equal(moved.receipt.completedFiles,1);
for(const name of Object.keys(f.originals).filter(name=>name!=='item-02.txt'))assert((await fs.stat(path.join(f.source,name))).isFile());
const inverse=await engine.undoPreview({journalId:moved.receipt.operationId});await engine.undo({journalId:moved.receipt.operationId,previewId:inverse.previewId,previewHash:inverse.previewHash,approved:true,resolution:'skip'});
assert.deepEqual(await hashSources(f),f.originals);
console.log(JSON.stringify({ok:true,scope:'disposable native fixture',ruleSelected:1,moved:1,unselectedPreserved:7,restored:1,invalidRulesRejected:3}));
