import { chromium, expect } from '@playwright/test';
import { existsSync } from 'node:fs';
import { mkdir, writeFile } from 'node:fs/promises';
import path from 'node:path';
process.env.PW_TEST_SCREENSHOT_NO_FONTS_READY='1';
const cached=path.join(process.env.LOCALAPPDATA,'ms-playwright/chromium-1248/chrome-win64/chrome.exe');
const browser=await chromium.launch({...(existsSync(cached)?{executablePath:cached}:{channel:'chrome'}),headless:true});
const folder=path.resolve('../../docs/evidence/files-owner-pilot/interaction');
await mkdir(folder,{recursive:true});
const checks=[];
try {
  const page=await browser.newPage({viewport:{width:1366,height:768},reducedMotion:'reduce'});
  await page.addInitScript(()=>{
    localStorage.setItem('knoux_theme','light'); localStorage.setItem('knoux_locale','en');
    localStorage.setItem('knoux.cinematic.v1',JSON.stringify({seen:true,always:false,muted:true,reduced:true}));
  });
  await page.goto('http://127.0.0.1:3029/#files',{waitUntil:'domcontentloaded'});
  const search=page.getByTestId('files-search'); await search.waitFor();
  await search.fill('Aurora'); await expect(page.locator('[data-testid^="files-row-"]')).toHaveCount(1);
  await search.fill('NO_SUCH_FILE_731'); await expect(page.locator('[data-testid^="files-row-"]')).toHaveCount(0);
  await expect(page.getByText('No fixture files match the current filters.')).toBeVisible();
  await search.fill(''); checks.push('Search and zero results use the existing query predicates');
  const breakdown=page.locator('.knx-files-distribution summary');
  await expect(breakdown).toBeVisible(); await breakdown.click();
  await expect(page.getByText('File Types Distribution',{exact:true})).toBeVisible();
  await breakdown.click(); checks.push('File type and age breakdown remains reachable in its bounded panel');
  await page.getByTestId('files-category-images').click();
  await expect(page.locator('[data-testid^="files-row-"]')).toHaveCount(4);
  await page.getByTestId('files-category-all').click();
  const scroll=page.getByTestId('files-results-scroll');
  const scrollBefore=await scroll.evaluate(e=>({height:e.clientHeight,total:e.scrollHeight,top:e.scrollTop}));
  await scroll.focus(); await page.keyboard.press('End');
  await scroll.evaluate(e=>e.scrollTo(0,e.scrollHeight));
  const scrollAfter=await scroll.evaluate(e=>e.scrollTop);
  if(scrollBefore.total<=scrollBefore.height || scrollAfter<=0) throw Error('Results are not an operable inner scroller');
  await page.locator('[data-testid^="files-row-"]').last().click();
  await page.screenshot({path:path.join(folder,'results-scrolled.png'),animations:'disabled'});
  checks.push({name:'Result list scroll/last row selection',scrollBefore,scrollAfter});
  await page.locator('.knx-files-advanced summary').click();
  await page.getByTestId('files-extension').selectOption('docx');
  await expect(page.locator('[data-testid^="files-row-"]')).toHaveCount(2);
  await page.getByTestId('files-extension').selectOption('All');
  await page.getByTestId('files-view-grid').click(); await page.getByTestId('files-view-list').click();
  await page.locator('.knx-files-advanced summary').click(); checks.push('Filters and grid/list controls remain functional');
  await page.getByRole('tab',{name:'Tools',exact:true}).click();
  await expect(page.locator('[data-testid^="files-service-"]')).toHaveCount(12);
  await page.getByTestId('files-service-file-hash').click();
  await expect(page.getByTestId('files-workbench')).toBeVisible();
  const sideWidth=await page.getByTestId('files-workbench').evaluate(e=>e.clientWidth);
  await page.getByRole('separator',{name:'Resize workbench'}).press('ArrowLeft');
  const resizedWidth=await page.getByTestId('files-workbench').evaluate(e=>e.clientWidth);
  if(resizedWidth >= sideWidth) throw Error('Pinned workbench resize was lost');
  checks.push({name:'Pinned workbench resize',sideWidth,resizedWidth});
  await page.getByTestId('workbench-mode-toggle').click();
  await expect(page.getByTestId('files-workbench-expanded')).toBeVisible();
  await page.getByTestId('files-workbench-tool-select').selectOption('file-metadata');
  await page.getByTestId('workbench-mode-toggle').click();
  await expect(page.getByTestId('files-workbench')).toBeVisible();
  await page.keyboard.press('Escape'); await expect(page.getByTestId('files-workbench')).toHaveCount(0);
  await page.getByRole('tab',{name:'Details',exact:true}).click();
  await page.getByRole('tab',{name:'Details',exact:true}).press('ArrowRight');
  await expect(page.getByRole('tab',{name:'Tools',exact:true})).toHaveAttribute('aria-selected','true');
  checks.push('All 12 services, side/expanded/pin, tool switching, Escape and tab keyboard navigation');
  await page.getByRole('tab',{name:'Details',exact:true}).click();
  const preview=page.locator('[data-preview-expanded]'); const initial=await preview.evaluate(e=>e.clientHeight);
  await page.getByRole('button',{name:'Expand preview',exact:true}).click();
  if(await preview.evaluate(e=>e.clientHeight)<=initial) throw Error('Preview expansion did not expand');
  await page.getByTestId('files-plan-cta').click();
  await expect(page.locator('[data-visual-section="studio"]')).toBeVisible();
  checks.push('Preview expands internally and organization action navigates to existing Studio');
} finally { await browser.close(); await writeFile(path.join(folder,'checks.json'),JSON.stringify(checks,null,2)); }
console.log(JSON.stringify(checks,null,2));
