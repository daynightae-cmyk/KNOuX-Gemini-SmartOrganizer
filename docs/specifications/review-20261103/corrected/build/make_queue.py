#!/usr/bin/env python3
"""Render Matrix/revalidation_queue.md and Matrix/matrix_181_v2.md from
matrix_181_v2.csv.

The queue is the operational list: which of the 181 entries must be re-verified
against source, in what order, and what specifically has to be read for each.
It is generated so it can never disagree with the CSV it comes from.
"""
import csv
import json
import os
from collections import Counter, defaultdict

REPO = r"D:/KNOUX-Workspace/KNOuX-Gemini-SmartOrganizer"
OUT = os.path.join(REPO, "_spec_review/out")
DEST = os.path.join(REPO, "_spec_review/corrected/Matrix")

# Work order: dependency first (shared engines and the founding domain), then the
# domains whose verified state is weakest. This is a sequence, not a calendar.
ORDER = ["03", "02", "06", "07", "08", "11", "09", "12", "10", "05", "13", "14", "04", "01"]
TITLES = {"01": "Home Command Center", "02": "Smart Scan", "03": "Organization Studio",
          "04": "Google Workspace", "05": "Applications", "06": "Files", "07": "Storage",
          "08": "Cleanup (Clean Room)", "09": "Startup (Boot Control)",
          "10": "System / Network / Hardware", "11": "Repair Lab (Recovery)",
          "12": "Services Commander", "13": "Automation (Flow Studio)",
          "14": "Settings / Engine / AI"}


def clip(text, n):
    """Truncate for display without ever cutting a path or token in half.

    A citation that ends `docs/evidence/studio-f` is worse than no citation: the
    reader cannot tell whether the file exists. Cut at the last separator before
    the limit and mark the omission.
    """
    text = (text or "").strip()
    if len(text) <= n:
        return text
    head = text[:n]
    for sep in (";", " ", ",", "/"):
        i = head.rfind(sep)
        if i >= n * 0.55:
            return head[:i].rstrip(",;/ ") + (" …" if sep == " " else " …")
    return head + " …"


def main():
    rows = list(csv.DictReader(open(os.path.join(OUT, "matrix_181_v2.csv"),
                                    encoding="utf-8")))
    summary = json.loads(open(os.path.join(OUT, "matrix_181_v2_summary.json"),
                              encoding="utf-8").read())
    os.makedirs(DEST, exist_ok=True)
    head = summary["measured_head"]
    by = defaultdict(list)
    for r in rows:
        by[r["spec_ref"][1:3]].append(r)

    # ---- revalidation queue ----
    q = ["# Revalidation Queue - 181 entries against the live tree\n",
         "Generated by `build/matrix_v2.py` + `build/make_queue.py` from the repository at "
         "measured HEAD `%s`. Re-run both after any commit; the queue is a product of the "
         "tree, not a hand-maintained list.\n" % head,
         "## Why this file exists\n",
         "The evidence archive's own ledger reports **%d of 181** entries as "
         "`NOT_REASSESSED_IN_THIS_SLICE` and **%d** as assessed in the newest slice. The "
         "reviewer's correction requires those two groups be treated differently, and it "
         "forbids downgrading previously verified work without evidence. So:\n" % (
             summary["revalidation_mandatory"], summary["confirm_not_regressed"]),
         "- **%d entries: `MANDATORY SOURCE REVALIDATION`.** Their historical classification is "
         "kept exactly as recorded and is *not* trusted as current state." % summary[
             "revalidation_mandatory"],
         "- **%d entries: `CONFIRM NOT REGRESSED`.** They were assessed in the newest slice with "
         "an implementation SHA. Those SHAs were tested for reachability and **all of them are "
         "ancestors of the current HEAD**, so the work is present in history. The task here is a "
         "test run, not an archaeology dig." % summary["confirm_not_regressed"],
         "",
         "## The two columns that must never be merged\n",
         "| Column | Question it answers | Who may change it |",
         "|---|---|---|",
         "| `historical_status`, `historical_slice_status`, `historical_implementation_sha`, "
         "`historical_evidence_path` | what the dated records asserted | only a finished "
         "revalidation, with a citation |",
         "| `current_runtime_verification` | what has been proven at this baseline | only an "
         "executed command with a recorded SHA and exit code |",
         "",
         "At this baseline `current_runtime_verification` reads `NOT RUN` for all 181. That is "
         "the honest state after a documentation pass, not a failure of the product.\n",
         "## Queue, in work order\n"]
    total_left = 0
    for i, m in enumerate(ORDER, 1):
        rs = sorted(by.get(m, []), key=lambda r: r["spec_ref"])
        if not rs:
            continue
        mand = [r for r in rs if r["revalidation"].startswith("MANDATORY")]
        conf = [r for r in rs if not r["revalidation"].startswith("MANDATORY")]
        total_left += len(mand)
        q.append("### %d. D%s %s - %d entries (%d mandatory revalidation, %d confirm-only)\n" % (
            i, m, TITLES[m], len(rs), len(mand), len(conf)))
        no_int = [r for r in rs if r["frontend_integration_point"].startswith("NONE")]
        no_gated = [r for r in rs if r["gated_test_scripts_naming_this_id"] == "none"]
        q.append("- Entries with **no located renderer integration point**: %d%s" % (
            len(no_int), "" if no_int else " - all located."))
        q.append("- Entries **not named by any gated npm test**: %d. Where an ungated script "
                 "already exists, promoting it is cheaper than writing a new suite." % len(no_gated))
        q.append("- Domain work: read the bridge, the preload namespace and the workbench "
                 "dispatcher for this domain; answer Volume 1 8.3 questions 1-3 and 15 for each "
                 "entry; write the answers into `Matrix/matrix_181_v2.csv`, not into a new "
                 "document.")
        if mand:
            q.append("")
            q.append("| ref | id | name | historical (unchanged) | what to read first |")
            q.append("|---|---|---|---|---|")
            for r in mand:
                q.append("| %s | `%s` | %s | %s | %s |" % (
                    r["spec_ref"], r["ledger_id"], r["service_name"],
                    clip(r["historical_status"], 58).replace("|", "/"),
                    clip(r["codex_inspection_task"], 190).replace("|", "/")))
        if conf:
            q.append("")
            q.append("**Confirm-only (do not downgrade without new evidence):**")
            for r in conf:
                q.append("- %s `%s` %s - recorded SHA %s is %s; evidence cited: %s" % (
                    r["spec_ref"], r["ledger_id"], r["service_name"],
                    (r["historical_implementation_sha"] or "none")[:9],
                    r["historical_sha_reachability"].lower(),
                    clip(r["historical_evidence_path"] or "none recorded", 150)))
        q.append("")
    q.append("## Totals\n")
    q.append("| item | value |")
    q.append("|---|---|")
    q.append("| mandatory source revalidation | %d |" % summary["revalidation_mandatory"])
    q.append("| confirm not regressed | %d |" % summary["confirm_not_regressed"])
    q.append("| located renderer integration points | %d |" %
             summary["rows_with_renderer_integration_point"])
    q.append("| verified absence of integration point | %d |" %
             summary["rows_without_renderer_integration_point"])
    q.append("| named by a gated test | %d |" % summary["rows_named_by_a_gated_test"])
    q.append("| named only by ungated tests | %d |" % summary["rows_named_only_by_ungated_tests"])
    q.append("| named by no test at all | %d |" % summary["rows_no_test_names_at_all"])
    with open(os.path.join(DEST, "revalidation_queue.md"), "w", encoding="utf-8") as fh:
        fh.write("\n".join(q) + "\n")

    # ---- compact per-domain matrix view (the CSV is the authority) ----
    m = ["# 181-Service Matrix v2 - readable view\n",
         "The authority is `matrix_181_v2.csv` (%d columns per row). This file is a "
         "navigation view of the same generated rows: nothing here is hand-entered, so it "
         "cannot disagree with the CSV.\n" % len(rows[0]),
         "Measured HEAD: `%s`  |  origin/main: `%s`  |  divergence: %s\n" % (
             head, summary["origin_main"],
             summary["ahead_behind_origin_main"].replace("\t", " behind /  ahead")),
         "## Per-domain supply\n",
         "| domain | entries | located integration points | named by gated test | "
         "registered capabilities in family |",
         "|---|---|---|---|---|"]
    for msn in ORDER:
        rs = by.get(msn, [])
        if not rs:
            continue
        m.append("| D%s %s | %d | %d | %d | %s |" % (
            msn, TITLES[msn], len(rs),
            sum(1 for r in rs if not r["frontend_integration_point"].startswith("NONE")),
            sum(1 for r in rs if r["gated_test_scripts_naming_this_id"] != "none"),
            rs[0]["native_family_capability_count"]))
    m.append("\n## Reversibility classes and what each one owes\n")
    counts = Counter(r["reversibility_class"] for r in rows)
    m.append("| class | entries | completion condition lives in |")
    m.append("|---|---|---|")
    for k, v in counts.most_common():
        m.append("| %s | %d | Contracts/*.md, line 'Completion condition for this class' |" % (k, v))
    m.append("\n## Reading one row\n")
    m.append("`spec_ref` domain identifier; `ledger_id` the ID registry value; "
             "`in_code_catalog_id` whether that id keys anything in the renderer; "
             "`frontend_integration_point` `path:line [kind]` where kind is one of WORKBENCH_MAP, "
             "CASE_WORKBENCH, CASE_JSX, TERNARY_BRANCH, ICON_SWITCH - **an ICON_SWITCH or rail "
             "hit is not a workbench**, which is why the strongest site is the one reported; "
             "`component_definition` where the mapped component is actually defined; "
             "`native_ops_referenced` identifiers literally present at that site; "
             "`renderer_binding_function_count` typed envelope-returning functions in that "
             "domain's binding file; `historical_*` copied from the ledger; "
             "`current_runtime_verification` what has been proven now; `revalidation` the flag; "
             "`codex_inspection_task` the concrete next read.")
    with open(os.path.join(DEST, "matrix_181_v2.md"), "w", encoding="utf-8") as fh:
        fh.write("\n".join(m) + "\n")
    print("queue + readable matrix written; mandatory=%d confirm=%d" % (
        summary["revalidation_mandatory"], summary["confirm_not_regressed"]))


if __name__ == "__main__":
    main()
